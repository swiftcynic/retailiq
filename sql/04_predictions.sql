-- Seven-day item-store batch forecasts. Run once before first prediction.
CREATE TABLE IF NOT EXISTS RETAILIQ.MART.DEMAND_FORECASTS (
    RUN_ID VARCHAR(64) NOT NULL,
    MODEL_VERSION VARCHAR(64) NOT NULL,
    ITEM_ID VARCHAR(128) NOT NULL,
    STORE_ID VARCHAR(128) NOT NULL,
    FORECAST_ORIGIN DATE NOT NULL,
    FORECAST_START_DATE DATE NOT NULL,
    FORECAST_END_DATE DATE NOT NULL,
    PREDICTED_UNITS FLOAT NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
-- Model metadata is kept separate from individual forecast rows.
CREATE TABLE IF NOT EXISTS RETAILIQ.MART.MODEL_RUNS (
    RUN_ID VARCHAR(64) NOT NULL,
    MODEL_VERSION VARCHAR(64) NOT NULL,
    MODEL_FILE_SHA256 VARCHAR(64) NOT NULL,
    FORECAST_ORIGIN DATE NOT NULL,
    SERIES_COUNT INTEGER NOT NULL,
    TRAINING_CUTOFF DATE,
    EVALUATION_WAPE FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
