CREATE DATABASE IF NOT EXISTS RETAILIQ;
CREATE SCHEMA IF NOT EXISTS RETAILIQ.RAW;
CREATE SCHEMA IF NOT EXISTS RETAILIQ.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAILIQ.MART;
CREATE WAREHOUSE IF NOT EXISTS RETAILIQ_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE TABLE IF NOT EXISTS RETAILIQ.RAW.DAILY_SALES (
  ITEM_ID VARCHAR, STORE_ID VARCHAR, DAY_KEY VARCHAR, SALE_DATE DATE, UNITS_SOLD NUMBER(12,0)
);
CREATE TABLE IF NOT EXISTS RETAILIQ.RAW.INGEST_LOG (
  BATCH_ID VARCHAR, LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), ROWS_LOADED NUMBER(12,0)
);
