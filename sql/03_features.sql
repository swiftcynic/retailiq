-- Every row is a forecast origin (the end of a completed sales day).
-- Past-only features use ROWS BETWEEN ... PRECEDING AND CURRENT ROW.
-- Targets use FOLLOWING rows and are restricted to full 7-day future windows.
-- The per-series calendar is checked for continuity before producing features.
CREATE OR REPLACE VIEW RETAILIQ.MART.DAILY_DEMAND_FEATURES AS
WITH ordered AS (
  SELECT
    ITEM_ID, STORE_ID, SALE_DATE AS AS_OF_DATE, UNITS_SOLD,
    ROW_NUMBER() OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE) AS DAY_NUMBER,
    COUNT(*) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                   ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) AS HIST_DAYS_28,
    MIN(SALE_DATE) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                         ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) AS HIST_START_DATE,
    LAG(1 * UNITS_SOLD, 1) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE) AS LAG_1,
    LAG(UNITS_SOLD, 7) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE) AS LAG_7,
    LAG(UNITS_SOLD, 14) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE) AS LAG_14,
    LAG(UNITS_SOLD, 28) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE) AS LAG_28,
    AVG(UNITS_SOLD) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                          ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS AVG_7,
    AVG(UNITS_SOLD) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                          ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) AS AVG_28,
    STDDEV_SAMP(UNITS_SOLD) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                                  ROWS BETWEEN 27 PRECEDING AND CURRENT ROW) AS STDDEV_28,
    COUNT(*) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                   ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS_7,
    MAX(SALE_DATE) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                         ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS TARGET_END_DATE,
    SUM(UNITS_SOLD) OVER (PARTITION BY ITEM_ID, STORE_ID ORDER BY SALE_DATE
                          ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS TARGET_NEXT_7D
  FROM RETAILIQ.STAGING.DAILY_SALES
)
SELECT
  ITEM_ID, STORE_ID, AS_OF_DATE, UNITS_SOLD,
  LAG_1, LAG_7, LAG_14, LAG_28,
  AVG_7, AVG_28, STDDEV_28,
  DAYOFWEEKISO(AS_OF_DATE) AS DAY_OF_WEEK,
  MONTH(AS_OF_DATE) AS MONTH_OF_YEAR,
  TARGET_NEXT_7D,
  IFF(FUTURE_DAYS_7 = 7 AND DATEDIFF('day', AS_OF_DATE, TARGET_END_DATE) = 7,
      TRUE, FALSE) AS LABEL_AVAILABLE
FROM ordered
WHERE HIST_DAYS_28 = 28
  AND DATEDIFF('day', HIST_START_DATE, AS_OF_DATE) = 27;

-- Only fully observed 7-day labels enter supervised model training.
CREATE OR REPLACE VIEW RETAILIQ.MART.TRAINING_FEATURES AS
SELECT * FROM RETAILIQ.MART.DAILY_DEMAND_FEATURES
WHERE LABEL_AVAILABLE = TRUE;
