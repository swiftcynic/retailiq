CREATE OR REPLACE VIEW RETAILIQ.STAGING.DAILY_SALES AS
SELECT ITEM_ID, STORE_ID, SALE_DATE, SUM(UNITS_SOLD) AS UNITS_SOLD
FROM RETAILIQ.RAW.DAILY_SALES
GROUP BY ITEM_ID, STORE_ID, SALE_DATE;

CREATE OR REPLACE VIEW RETAILIQ.MART.WEEKLY_DEMAND AS
SELECT ITEM_ID, STORE_ID, DATE_TRUNC('WEEK', SALE_DATE)::DATE AS WEEK_START,
       SUM(UNITS_SOLD) AS WEEKLY_UNITS
FROM RETAILIQ.STAGING.DAILY_SALES
GROUP BY ITEM_ID, STORE_ID, DATE_TRUNC('WEEK', SALE_DATE)::DATE;
